// cgnatPrefix is Tailscale's IPv4 address space (RFC 6598 CGNAT). Node IPs and
// Service VIPs live here, so a literal address in this range is always sent to
// the proxy, never DIRECT.
var cgnatPrefix = netip.MustParsePrefix("100.64.0.0/10")

// pacConfig is the fail-closed rule set rendered into /proxy.pac.
type pacConfig struct {
	suffixes []string // tailnet DNS suffixes, lower-case, no trailing dot
	proxies  []string // ordered proxy list, e.g. "PROXY 127.0.0.1:8080"
}

func (c pacConfig) proxyList() string { return strings.Join(c.proxies, "; ") }

// effectiveSuffixes returns the configured suffixes plus "ts.net", de-duplicated.
// Matching all of ts.net is deliberate: ts.net is HSTS-preloaded and a Funnel
// name can resolve publicly, so tailnet-named traffic must never fall through
// to DIRECT.
func (c pacConfig) effectiveSuffixes() []string {
	return mergeSuffixes(c.suffixes, []string{"ts.net"})
}

// mergeSuffixes normalizes (lower-case, trimmed, no trailing dot) and
// de-duplicates DNS suffixes across groups while preserving group order.
func mergeSuffixes(groups ...[]string) []string {
	seen := map[string]bool{}
	var out []string
	for _, group := range groups {
		for _, s := range group {
			s = strings.ToLower(strings.TrimSuffix(strings.TrimSpace(s), "."))
			if s == "" || seen[s] {
				continue
			}
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

type pacState struct {
	cfg    pacConfig
	script string
}

// pacHolder stores the live PAC configuration and rendered script behind an
// atomic pointer so dynamic MagicDNS suffix discovery can swap /proxy.pac
// without locks or data races.
type pacHolder struct {
	state atomic.Pointer[pacState]
}

func newPACHolder(cfg pacConfig) *pacHolder {
	h := &pacHolder{}
	h.Update(cfg)
	return h
}

func (h *pacHolder) Update(cfg pacConfig) {
	cloned := pacConfig{
		suffixes: slices.Clone(cfg.suffixes),
		proxies:  slices.Clone(cfg.proxies),
	}
	h.state.Store(&pacState{
		cfg:    cloned,
		script: cloned.script(),
	})
}

func (h *pacHolder) Script() string {
	if st := h.state.Load(); st != nil {
		return st.script
	}
	return ""
}

func (h *pacHolder) Config() pacConfig {
	if st := h.state.Load(); st != nil {
		return st.cfg
	}
	return pacConfig{}
}

// script renders the PAC file served at /proxy.pac.
func (c pacConfig) script() string {
	var b strings.Builder
	b.WriteString("// Generated by ts-unplug-proxy. Do not edit.\n")
	b.WriteString("// Tailnet hosts fail closed: they are always sent to the proxy, never DIRECT.\n")
	b.WriteString("function isIpLiteral(h) {\n")
	b.WriteString("  var p = h.split(\".\");\n")
	b.WriteString("  if (p.length !== 4) return false;\n")
	b.WriteString("  for (var i = 0; i < 4; i++) {\n")
	b.WriteString("    var s = p[i];\n")
	b.WriteString("    if (s.length < 1 || s.length > 3) return false;\n")
	b.WriteString("    for (var j = 0; j < s.length; j++) {\n")
	b.WriteString("      var c = s.charCodeAt(j);\n")
	b.WriteString("      if (c < 48 || c > 57) return false;\n")
	b.WriteString("    }\n")
	b.WriteString("    if (parseInt(s, 10) > 255) return false;\n")
	b.WriteString("  }\n")
	b.WriteString("  return true;\n")
	b.WriteString("}\n")
	b.WriteString("function normalizeHost(h) {\n")
	b.WriteString("  h = h.toLowerCase();\n")
	b.WriteString("  if (h.length > 1 && h.charAt(h.length - 1) === \".\") h = h.slice(0, -1);\n")
	b.WriteString("  if (h.length > 1 && h.charAt(0) === \"[\" && h.charAt(h.length - 1) === \"]\") h = h.slice(1, -1);\n")
	b.WriteString("  return h;\n")
	b.WriteString("}\n")
	b.WriteString("var tsnetSuffixes = [" + jsStringList(c.effectiveSuffixes()) + "];\n")
	b.WriteString("var tsnetProxies = " + strconv.Quote(c.proxyList()) + ";\n")
	b.WriteString("function FindProxyForURL(url, host) {\n")
	b.WriteString("  host = normalizeHost(host);\n")
	b.WriteString("  for (var i = 0; i < tsnetSuffixes.length; i++) {\n")
	b.WriteString("    var d = tsnetSuffixes[i];\n")
	b.WriteString("    if (host === d || dnsDomainIs(host, \".\" + d)) return tsnetProxies;\n")
	b.WriteString("  }\n")
	b.WriteString("  // isInNet() only runs for IP literals, so hostnames never trigger a PAC DNS lookup.\n")
	b.WriteString("  if (isIpLiteral(host) && isInNet(host, \"100.64.0.0\", \"255.192.0.0\")) return tsnetProxies;\n")
	b.WriteString("  if (host.indexOf(\":\") !== -1 && host.indexOf(\"fd7a:115c:a1e0:\") === 0) return tsnetProxies;\n")
	b.WriteString("  return \"DIRECT\";\n")
	b.WriteString("}\n")
	return b.String()
}

// match mirrors the generated script in Go so doctor can report the decision
// without a JavaScript engine.
func (c pacConfig) match(host string) string {
	host = strings.ToLower(strings.TrimSuffix(host, "."))
	host = strings.TrimPrefix(strings.TrimSuffix(host, "]"), "[")
	for _, d := range c.effectiveSuffixes() {
		if host == d || strings.HasSuffix(host, "."+d) {
			return c.proxyList()
		}
	}
	if ip, err := netip.ParseAddr(host); err == nil {
		if ip.Is4() && cgnatPrefix.Contains(ip) {
			return c.proxyList()
		}
		if ip.Is6() && tailnetV6.Contains(ip) {
			return c.proxyList()
		}
	}
	return "DIRECT"
}

func jsStringList(items []string) string {
	quoted := make([]string, 0, len(items))
	for _, s := range items {
		quoted = append(quoted, strconv.Quote(s))
	}
	return strings.Join(quoted, ", ")
}

// startPACServer serves the PAC file and a JSON status document on an
// already-created listener.
func startPACServer(listener net.Listener, holder *pacHolder, status *statusState, includeAuthURL bool, verbose bool, serveErr chan<- serveResult) {
	mux := http.NewServeMux()
	serve := func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/x-ns-proxy-autoconfig")
		w.Header().Set("Cache-Control", "no-store")
		if _, err := io.WriteString(w, holder.Script()); err != nil && verbose {
			slog.Debug("pac write failed", slog.Any("error", err))
		}
	}
	mux.HandleFunc("/proxy.pac", serve)
	mux.HandleFunc("/status", statusHandler(status, includeAuthURL))
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/" {
			http.NotFound(w, r)
			return
		}
		serve(w, r)
	})
	server := &http.Server{Handler: mux}
	go func() {
		serveErr <- serveResult{name: "pac", err: server.Serve(listener)}
	}()
}

// pacProxies builds the ordered proxy list from the configured listeners. PAC
// clients are local, so a non-loopback bind address is advertised on loopback.
func pacProxies(socksAddr, httpAddr string) []string {
	var out []string
	if httpAddr != "" {
		out = append(out, "PROXY "+pacAdvertiseAddr(httpAddr))
	}
	if socksAddr != "" {
		out = append(out, "SOCKS5 "+pacAdvertiseAddr(socksAddr))
	}
	return out
}

func pacAdvertiseAddr(listenAddr string) string {
	host, port, err := net.SplitHostPort(listenAddr)
	if err != nil {
		return listenAddr
	}
	if ip, err := netip.ParseAddr(host); err == nil && ip.IsLoopback() {
		return listenAddr
	}
	if strings.EqualFold(host, "localhost") {
		return listenAddr
	}
	return net.JoinHostPort("127.0.0.1", port)
}
